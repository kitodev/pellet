// Collects every admin-editable text (with its default) from the website source
// and writes src/lib/content/text-defaults.ts (+ the admin copy). Run: pnpm texts
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const files = [];
async function walk(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (!["ui", "admin"].includes(e.name)) await walk(p);
    } else if (/\.tsx?$/.test(e.name) && !e.name.endsWith(".gen.ts")) files.push(p);
  }
}
await walk(path.join(root, "src"));

const texts = new Map();
const add = (k, v) => {
  if (k && !texts.has(k)) texts.set(k, v);
};
const unq = (s) => JSON.parse(`"${s.replace(/^"|"$/g, "")}"`);

for (const file of files) {
  const src = await readFile(file, "utf8");
  const routePath = /createFileRoute\(["']([^"']+)["']\)/.exec(src)?.[1]?.replace(/\/$/, "");
  for (const m of src.matchAll(/<Text id="([^"]+)">\s*\{\s*("(?:[^"\\]|\\.)*")\s*\}\s*<\/Text>/g))
    add(m[1], unq(m[2]));
  for (const m of src.matchAll(
    /useText\(\s*["']([^"']+)["'],\s*(["'])((?:(?!\2)[^\\]|\\.)*)\2\s*,?\s*\)/g,
  ))
    if (m[3]) add(m[1], m[3]);
  for (const m of src.matchAll(
    /<PageHero\s+(?:id="([^"]+)"\s+)?eyebrow="([^"]*)"\s+title="([^"]*)"(?:\s+text="([^"]*)")?/g,
  )) {
    const key = m[1] ?? routePath;
    if (!key) continue;
    add(`${key}.eyebrow`, m[2]);
    add(`${key}.title`, m[3]);
    if (m[4]) add(`${key}.text`, m[4]);
  }
  // Arrays of { t: '...', d: '...' } used with ids like `prefix.${i}.t`
  const dyn = /<Text id=\{`([\w.-]+)\.\$\{i\}\.t`\}>/.exec(src);
  if (dyn) {
    let i = 0;
    for (const m of src.matchAll(
      /\bt: (["'])((?:(?!\1)[^\\]|\\.)*)\1,\s*d: (["'])((?:(?!\3)[^\\]|\\.)*)\3/g,
    )) {
      add(`${dyn[1]}.${i}.t`, m[2]);
      add(`${dyn[1]}.${i}.d`, m[4]);
      i++;
    }
  }
}

// Texts without a visible default (shown only when filled in the admin)
for (const k of [
  "contact.phone",
  "contact.email",
  "contact.address",
  "contact.hours",
  "contact.map",
  "about.history",
  "about.references",
  "about.certifications",
])
  add(k, "");

const sorted = [...texts.entries()].sort(([a], [b]) => a.localeCompare(b));
const body = `// GENERATED by scripts/gen-text-defaults.mjs (pnpm texts) – do not edit by hand.
// Every admin-editable text key with its default value.
import { areas } from '@/lib/content/catalog';

export const textDefaults: Record<string, string> = {
${sorted.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}
};

for (const area of Object.values(areas)) {
  for (const field of ['title', 'label', 'intro'] as const) textDefaults[\`area.\${area.key}.\${field}\`] = area[field];
  for (const category of area.categories) for (const field of ['name', 'short', 'description'] as const) textDefaults[\`category.\${area.key}.\${category.slug}.\${field}\`] = category[field];
}
`;
await writeFile(path.join(root, "src/lib/content/text-defaults.ts"), body);
await writeFile(
  path.join(root, "admin/lib/content/text-defaults.ts"),
  body.replace("from '@/lib/content/catalog'", 'from "@/lib/content/menu"'),
).catch(() => {});
console.log(`${sorted.length} szöveg + kategóriák → text-defaults.ts`);
